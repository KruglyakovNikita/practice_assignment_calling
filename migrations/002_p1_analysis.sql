BEGIN;

ALTER TABLE public.call_attempts
  ADD CONSTRAINT call_attempts_id_org_unique UNIQUE (id, org_id);

CREATE TABLE public.analyses (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id uuid NOT NULL,
  call_attempt_id uuid NOT NULL UNIQUE,
  status text NOT NULL DEFAULT 'queued'
    CHECK (status IN ('queued', 'streaming', 'completed', 'partial', 'error', 'cancelled')),
  partial_result jsonb NOT NULL DEFAULT '{}'::jsonb,
  result jsonb NULL,
  error_code text NULL,
  error_message text NULL,
  cancel_requested boolean NOT NULL DEFAULT false,
  provider_started_at timestamptz NULL,
  lease_until timestamptz NULL,
  lease_token uuid NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT analyses_attempt_org_fk FOREIGN KEY (call_attempt_id, org_id)
    REFERENCES public.call_attempts(id, org_id),
  CONSTRAINT analyses_id_org_unique UNIQUE (id, org_id)
);

CREATE TABLE public.analysis_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  analysis_id uuid NOT NULL,
  org_id uuid NOT NULL,
  event_type text NOT NULL CHECK (event_type IN ('chunk', 'done', 'error')),
  payload jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT analysis_events_analysis_org_fk FOREIGN KEY (analysis_id, org_id)
    REFERENCES public.analyses(id, org_id) ON DELETE CASCADE
);

CREATE INDEX analyses_queue_idx
  ON public.analyses(created_at, id)
  WHERE status = 'queued';

CREATE INDEX analyses_expired_stream_idx
  ON public.analyses(lease_until, id)
  WHERE status = 'streaming';

CREATE INDEX analysis_events_replay_idx
  ON public.analysis_events(analysis_id, id);

ALTER TABLE public.analyses ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.analyses FORCE ROW LEVEL SECURITY;
ALTER TABLE public.analysis_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.analysis_events FORCE ROW LEVEL SECURITY;

CREATE POLICY analyses_tenant_policy ON public.analyses
  TO auto_calling_app
  USING (org_id = (SELECT app_private.current_org_id()))
  WITH CHECK (org_id = (SELECT app_private.current_org_id()));

CREATE POLICY analysis_events_tenant_policy ON public.analysis_events
  TO auto_calling_app
  USING (org_id = (SELECT app_private.current_org_id()))
  WITH CHECK (org_id = (SELECT app_private.current_org_id()));

GRANT SELECT, INSERT, UPDATE ON public.analyses TO auto_calling_app;
GRANT SELECT, INSERT ON public.analysis_events TO auto_calling_app;
GRANT USAGE, SELECT ON SEQUENCE public.analysis_events_id_seq TO auto_calling_app;

GRANT SELECT, UPDATE ON public.analyses TO auto_calling_service;
GRANT SELECT, INSERT ON public.analysis_events TO auto_calling_service;
GRANT USAGE, SELECT ON SEQUENCE public.analysis_events_id_seq TO auto_calling_service;

COMMIT;
